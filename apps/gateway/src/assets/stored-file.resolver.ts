import { Inject } from '@nestjs/common';
import type { ConfigType } from '@nestjs/config';
import { Parent, ResolveField, Resolver } from '@nestjs/graphql';
import type { StoredObject } from '../clients/asset-service/domain/stored-object.interface';
import { mediaConfig } from '../config/config.namespaces';
import { PUBLIC_KEY_PREFIX } from './assets.constants';
import { StoredFileModel } from './models/stored-file.model';

/**
 * `StoredFile.url` for public files: the media base URL plus the key (ADR 010). Computed
 * locally from config, with no call to asset-service and nothing to sign, so the URL is
 * stable and cacheable by the CDN and browsers. Files outside `public/` (the original
 * upload) get null: they are only reachable through a short-lived signed URL.
 */
@Resolver(() => StoredFileModel)
export class StoredFileResolver {
  constructor(@Inject(mediaConfig.KEY) private readonly config: ConfigType<typeof mediaConfig>) {}

  @ResolveField(() => String, {
    nullable: true,
    description: 'Public URL (CDN); null for private files such as the original upload.',
  })
  url(@Parent() file: StoredObject): string | null {
    const segments = file.key.split('/');

    // Keys are generated by asset-service (ids and an extension), but a key still can't change
    // the URL's meaning: dot segments would climb out of public/ (encoding leaves dots as they
    // are), and every other segment is encoded, so "?" or "#" can't start a query or fragment.
    if (
      !file.key.startsWith(PUBLIC_KEY_PREFIX) ||
      segments.some((segment) => segment === '' || segment === '.' || segment === '..')
    ) {
      return null;
    }

    return `${this.config.baseUrl}${segments.map(encodeURIComponent).join('/')}`;
  }
}
